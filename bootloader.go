// LoadBootSectors gets the three boot sectors from raw bytes, an ATR, or an
// Atari executable (native BW-DOS FORMAT.COM uses that last one).
func LoadBootSectors(path string) ([]byte, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	if len(data) >= 16+384 && data[0] == 0x96 && data[1] == 0x02 {
		boot := data[16 : 16+384]
		if boot[0] != 0 {
			return nil, fmt.Errorf("%s has no Atari boot sectors", path)
		}
		return append([]byte(nil), boot...), nil
	}
	if len(data) == 384 && data[0] == 0 && data[1] == 3 {
		return append([]byte(nil), data...), nil
	}
	for offset := 0; offset < len(data); {
		if offset+2 <= len(data) && data[offset] == 0xff && data[offset+1] == 0xff {
			offset += 2
		}
		if offset+4 > len(data) {
			break
		}
		start := int(binary.LittleEndian.Uint16(data[offset : offset+2]))
		end := int(binary.LittleEndian.Uint16(data[offset+2 : offset+4]))
		offset += 4
		if end < start || end-start+1 > len(data)-offset {
			return nil, errors.New("invalid Atari executable segment")
		}
		segment := data[offset : offset+end-start+1]
		if len(segment) >= 384 && segment[0] == 0 && segment[1] == 3 {
			return append([]byte(nil), segment[:384]...), nil
		}
		offset += len(segment)
	}
	return nil, fmt.Errorf("%s has no 3-sector boot loader", path)
}

